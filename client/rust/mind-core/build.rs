// filesystem-only (no content registry), so plain `cargo build` works; only
// `mind-tools pack` updates the inputs.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default());
    // client/rust/mind-core -> repo root.
    let root = match manifest_dir.join("../../..").canonicalize() {
        Ok(root) => root,
        Err(error) => fail(&format!("resolving repo root: {error}")),
    };
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default());

    let mut source = String::from(
        "// @generated by mind-core/build.rs — do not edit.\n\
         // Ported from Mindustry `AssetsProcess.java` (plan 03 §6.8).\n",
    );

    match generate_sounds(&root) {
        Ok((code, inputs)) => {
            source.push_str(&code);
            emit_rerun(&inputs);
        }
        Err(error) => fail(&error),
    }
    match generate_musics(&root) {
        Ok((code, inputs)) => {
            source.push_str(&code);
            emit_rerun(&inputs);
        }
        Err(error) => fail(&error),
    }
    match generate_tex(&root) {
        Ok((code, inputs)) => {
            source.push_str(&code);
            emit_rerun(&inputs);
        }
        Err(error) => fail(&error),
    }
    match generate_icon(&root) {
        Ok((code, inputs)) => {
            source.push_str(&code);
            emit_rerun(&inputs);
        }
        Err(error) => fail(&error),
    }
    match generate_iconc(&root) {
        Ok((code, inputs)) => {
            source.push_str(&code);
            emit_rerun(&inputs);
        }
        Err(error) => fail(&error),
    }

    let target = out_dir.join("asset_ids.rs");
    if let Err(error) = fs::write(&target, source) {
        fail(&format!("writing {}: {error}", target.display()));
    }
}

fn fail(message: &str) -> ! {
    eprintln!("mind-core build.rs: error: {message}");
    std::process::exit(1);
}

fn emit_rerun(inputs: &[PathBuf]) {
    for path in inputs {
        println!("cargo:rerun-if-changed={}", path.display());
    }
}

/// Java `SourceVersion.isKeyword` (keywords + `true`/`false`/`null`).
fn is_java_keyword(name: &str) -> bool {
    matches!(
        name,
        "abstract"
            | "assert"
            | "boolean"
            | "break"
            | "byte"
            | "case"
            | "catch"
            | "char"
            | "class"
            | "const"
            | "continue"
            | "default"
            | "do"
            | "double"
            | "else"
            | "enum"
            | "extends"
            | "final"
            | "finally"
            | "float"
            | "for"
            | "goto"
            | "if"
            | "implements"
            | "import"
            | "instanceof"
            | "int"
            | "interface"
            | "long"
            | "native"
            | "new"
            | "package"
            | "private"
            | "protected"
            | "public"
            | "return"
            | "short"
            | "static"
            | "strictfp"
            | "super"
            | "switch"
            | "synchronized"
            | "this"
            | "throw"
            | "throws"
            | "transient"
            | "try"
            | "void"
            | "volatile"
            | "while"
            | "true"
            | "false"
            | "null"
    )
}

/// `AssetsProcess`: keyword names get an `s` appended.
fn mangle_field(name: &str) -> String {
    if is_java_keyword(name) {
        format!("{name}s")
    } else {
        name.to_owned()
    }
}

/// `AssetsProcess.capitalize`/`Strings.kebabToCamel`: drop `-`/`_`, uppercase
/// the character after them (first character untouched).
fn camel(name: &str) -> String {
    let mut result = String::with_capacity(name.len());
    let mut after_separator = false;
    for c in name.chars() {
        if c == '_' || c == '-' {
            after_separator = true;
            continue;
        }
        if after_separator {
            result.extend(c.to_uppercase());
        } else {
            result.push(c);
        }
        after_separator = false;
    }
    result
}

/// `UPPER_SNAKE` conversion for Rust constants (`uiBack` -> `UI_BACK`).
fn upper_snake(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 4);
    let mut prev_lower_or_digit = false;
    for c in name.chars() {
        if c.is_ascii_uppercase() {
            if prev_lower_or_digit && !out.ends_with('_') {
                out.push('_');
            }
            out.push(c);
            prev_lower_or_digit = false;
        } else if c.is_ascii_lowercase() || c.is_ascii_digit() {
            out.push(c.to_ascii_uppercase());
            prev_lower_or_digit = true;
        } else {
            out.push('_');
            prev_lower_or_digit = false;
        }
    }
    out
}

/// Collects `(const_name, literal)` pairs into a sorted module body.
fn render_module(module: &str, mut consts: Vec<(String, String)>) -> String {
    consts.sort();
    let mut seen = BTreeMap::new();
    let mut body = format!("pub mod {module} {{\n");
    for (name, value) in consts {
        let mut final_name = name.clone();
        let count = seen.entry(name).or_insert(0u32);
        *count += 1;
        if *count > 1 {
            final_name = format!("{final_name}_{count}");
        }
        body.push_str(&format!("    pub const {final_name}: {value};\n"));
    }
    body.push_str("}\n");
    body
}

fn string_const(name: &str, value: &str) -> (String, String) {
    (
        upper_snake(name),
        format!(
            "&str = \"{}\"",
            value.replace('\\', "\\\\").replace('"', "\\\"")
        ),
    )
}

/// `processSounds("Sounds", assets/sounds, genid=true)`.
fn generate_sounds(root: &Path) -> Result<(String, Vec<PathBuf>), String> {
    let dir = root.join("assets/sounds");
    let mut files = Vec::new();
    collect_audio(&dir, &mut files)?;
    files.sort_by(|a, b| a.file_name().cmp(&b.file_name()));
    let mut consts = vec![string_const("none", "none"), string_const("unset", "unset")];
    let mut names = std::collections::BTreeSet::new();
    for file in &files {
        let stem = file_stem(file)?;
        if !names.insert(stem.clone()) {
            return Err(format!("duplicate sound file name `{stem}`"));
        }
        consts.push(string_const(&mangle_field(&stem), &stem));
    }
    let mut inputs = files;
    inputs.push(dir.clone());
    // Regenerate only when the entry lands on disk (avoid an empty generated
    // file if the scan finds nothing).
    Ok((render_module("sounds", consts), inputs))
}

/// `processSounds("Musics", assets/music, genid=false)`.
fn generate_musics(root: &Path) -> Result<(String, Vec<PathBuf>), String> {
    let dir = root.join("assets/music");
    let mut files = Vec::new();
    collect_audio(&dir, &mut files)?;
    files.sort_by(|a, b| a.file_name().cmp(&b.file_name()));
    let mut consts = Vec::new();
    let mut names = std::collections::BTreeSet::new();
    for file in &files {
        let stem = file_stem(file)?;
        if !names.insert(stem.clone()) {
            return Err(format!("duplicate music file name `{stem}`"));
        }
        consts.push(string_const(&mangle_field(&stem), &stem));
    }
    let mut inputs = files;
    inputs.push(dir.clone());
    Ok((render_module("musics", consts), inputs))
}

/// `processUI` Tex half: every `assets-raw/sprites/ui/**/*.png` stem.
fn generate_tex(root: &Path) -> Result<(String, Vec<PathBuf>), String> {
    let dir = root.join("assets-raw/sprites/ui");
    let mut files = Vec::new();
    collect_ext(&dir, "png", &mut files)?;
    files.sort();
    let mut consts = Vec::new();
    for file in &files {
        // `AssetsProcess`: `filename.substring(0, filename.indexOf("."))` —
        // truncation is at the FIRST dot (`bar.9.png` -> `bar`).
        let file_name = file
            .file_name()
            .and_then(|name| name.to_str())
            .ok_or_else(|| format!("bad file name {}", file.display()))?;
        let stem = file_name.split('.').next().unwrap_or(file_name);
        let name = camel(stem);
        let name = if is_java_keyword(&name) {
            format!("{name}s")
        } else {
            name
        };
        consts.push(string_const(&name, stem));
    }
    let mut inputs = files;
    inputs.push(dir.clone());
    Ok((render_module("tex", consts), inputs))
}

/// `processUI` Icon half: `fontgen/config.json` glyphs (selected, unique).
fn generate_icon(root: &Path) -> Result<(String, Vec<PathBuf>), String> {
    let path = root.join("assets-raw/fontgen/config.json");
    let text = fs::read_to_string(&path)
        .map_err(|error| format!("reading {}: {error}", path.display()))?;
    let value: serde_json::Value = serde_json::from_str(&text)
        .map_err(|error| format!("parsing {}: {error}", path.display()))?;
    let glyphs = value
        .get("glyphs")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| format!("{}: missing `glyphs`", path.display()))?;
    let mut consts = Vec::new();
    let mut seen = std::collections::BTreeSet::new();
    for glyph in glyphs {
        let selected = glyph
            .get("selected")
            .and_then(serde_json::Value::as_bool)
            .unwrap_or(true);
        if !selected {
            continue;
        }
        let css = glyph
            .get("css")
            .and_then(serde_json::Value::as_str)
            .unwrap_or_default();
        let name = camel(css);
        if name.is_empty() || !seen.insert(name.clone()) {
            continue;
        }
        let code = glyph
            .get("code")
            .and_then(serde_json::Value::as_u64)
            .unwrap_or(0) as u32;
        consts.push((upper_snake(&name), format!("char = '\\u{{{code:x}}}'")));
    }
    Ok((render_module("icon", consts), vec![path]))
}

/// `processUI` Iconc half: `icons.properties` texture names.
fn generate_iconc(root: &Path) -> Result<(String, Vec<PathBuf>), String> {
    let path = root.join("assets/icons/icons.properties");
    let text = fs::read_to_string(&path)
        .map_err(|error| format!("reading {}: {error}", path.display()))?;
    let mut consts = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let Ok(code) = key.trim().parse::<u32>() else {
            continue;
        };
        let Some(texture) = value.split('|').nth(1) else {
            continue;
        };
        let name = camel(texture)
            .replace("Medium", "")
            .replace("Icon", "")
            .replace("Ui", "");
        if name.is_empty() {
            continue;
        }
        let name = if is_java_keyword(&name) || name == "char" {
            format!("{name}i")
        } else {
            name
        };
        consts.push((upper_snake(&name), format!("char = '\\u{{{code:x}}}'")));
    }
    Ok((render_module("iconc", consts), vec![path]))
}

fn file_stem(path: &Path) -> Result<String, String> {
    path.file_stem()
        .and_then(|stem| stem.to_str())
        .map(str::to_owned)
        .ok_or_else(|| format!("bad file name {}", path.display()))
}

fn collect_audio(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), String> {
    if !dir.is_dir() {
        return Ok(());
    }
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .map_err(|error| format!("reading {}: {error}", dir.display()))?
        .map(|entry| entry.map(|e| e.path()))
        .collect::<std::io::Result<_>>()
        .map_err(|error| error.to_string())?;
    entries.sort();
    for path in entries {
        if path.is_dir() {
            collect_audio(&path, out)?;
        } else if path
            .extension()
            .is_some_and(|ext| ext == "ogg" || ext == "mp3")
        {
            out.push(path);
        }
    }
    Ok(())
}

fn collect_ext(dir: &Path, ext: &str, out: &mut Vec<PathBuf>) -> Result<(), String> {
    if !dir.is_dir() {
        return Ok(());
    }
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .map_err(|error| format!("reading {}: {error}", dir.display()))?
        .map(|entry| entry.map(|e| e.path()))
        .collect::<std::io::Result<_>>()
        .map_err(|error| error.to_string())?;
    entries.sort();
    for path in entries {
        if path.is_dir() {
            collect_ext(&path, ext, out)?;
        } else if path.extension().is_some_and(|found| found == ext) {
            out.push(path);
        }
    }
    Ok(())
}
