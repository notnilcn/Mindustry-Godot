//! Mindustry-Godot's SpacetimeDB client facade (`mind-stdb`), the Rust replacement for
//! the legacy C# `sstdbsdk`.
//!
//! P0 is a compiling skeleton: configuration, token persistence, the subscription-wave
//! table lists and the typed-binder trait exist, while every live/network operation
//! returns [`MindDbError::NotImplemented`]. Plan
//! `01_PLATFORM_STDB_IMPLEMENTATION_PLAN.md` fills in the connector state machine,
//! generated-bindings subscriptions and the command relay. Invariants:
//!
//! - No `godot` dependency (gdext wraps this crate, never the reverse).
//! - No `tokio` type in the public API (OD-R4): the eventual worker thread + channels
//!   stay an implementation detail.
//! - The game boots and plays single-player with [`MindDbState::Offline`] and no server.
//!
//! Generated bindings live in [`module_bindings`] (checked in, never hand-edited;
//! regenerate with `server/build.sh`, drift gate `server/build.sh --check`).

pub mod binder;
pub mod config;
pub mod conn;
// Generated by `spacetime generate` (authoritative formatting; never hand-edit).
#[rustfmt::skip]
pub mod module_bindings;
pub mod tokens;
pub mod waves;

pub use binder::{BinderHandle, RowChange, TableBinder};
pub use config::ConnectionConfig;
pub use conn::{MindDb, MindDbError, MindDbState};
pub use tokens::{TokenStore, token_key};
pub use waves::SubscriptionWave;

/// Version of the `mind-stdb` crate, taken from `Cargo.toml`.
pub const MIND_VERSION: &str = env!("CARGO_PKG_VERSION");
