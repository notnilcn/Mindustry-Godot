//! Mindustry-Godot's SpacetimeDB client facade (`mind-stdb`), the Rust
//! replacement for the legacy C# `sstdbsdk`.
//!
//! Plan `01_PLATFORM_STDB_IMPLEMENTATION_PLAN.md` owns the surface:
//! connector lifecycle (§3.4), subscription waves (§3.6), typed binders (§3.5)
//! and the ordered command relay (§3.8). Invariants:
//!
//! - No `godot` dependency (gdext wraps this crate, never the reverse).
//! - No `tokio` type in the public API (OD-R4): the SDK owns its transport
//!   runtime internally; `pump()` polls it with `frame_tick()`.
//! - The game boots and plays single-player with [`StdbMode::Offline`] and no
//!   server running (§3.12 invariant 8).
//!
//! Generated bindings live in [`module_bindings`] (checked in, never hand-edited;
//! regenerate with `server/build.sh`, drift gate `server/build.sh --check`).

